REDUCE_PROMPT = """下面是同一场会议各片段的抽取结果（按时间顺序）。请合并去重、剔除重复与噪声，再按系统要求输出最终纪要。"""


def user_direct(transcript: str, meta: str = "") -> str:
    """一次性总结（短会议）的用户消息。"""
    head = f"【会议信息】{meta}\n\n" if meta else ""
    return f"{head}【会议转写】\n{transcript}"


def user_map(chunk: str, index: int, total: int) -> str:
    return f"【片段 {index}/{total}】\n{chunk}"


def user_reduce(notes: str, meta: str = "") -> str:
    head = f"【会议信息】{meta}\n\n" if meta else ""
    return f"{head}【各片段抽取结果】\n{notes}"
