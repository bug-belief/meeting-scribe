/* 唤起判定（O-12 D-2）。
 *
 * 「什么时候该让助理接话」是这个产品最容易出错、也最难事后发现的地方：
 * 判错了不会报错，只会在某个不该开口的场合突然插一句。
 *
 * 所以这条规则必须**能被单独测试**。原来它嵌在 2,100 行的 app.js 里，
 * 测试得靠「从源码里把函数原文抽出来 new Function 执行」——
 * 函数一搬家测试就假红（O-11 已经踩过一次同类坑）。
 * 拆成独立文件后，测试可以直接 require 这一份。
 *
 * 规则（mode 由页面上的开关决定）：
 *   strict  只听我的 —— 对方说「你们有助理吗」不该触发代答
 *   proxy   代理模式 —— 我不方便说话时，对方开口由助理替我应答
 *   其余     不限谁说的
 */
(() => {
  /* 唤醒词表。
   *
   * ⚠️ **必须容错**（2026-10-21 实测教训）：实时流式 ASR 对「助理」两个字识别不稳，
   * 同一句话在实时和最终稿里能差一个字。实测那次最终稿写的是「语音助理」，
   * 但实时出的很可能是「语音助厉 / 语音助力 / 语音著理」—— 原来只认精确的
   * 「语音助理」，于是**听到了却不唤醒**；更糟的是服务端当时不记实时文本，
   * 现象看起来就是"完全没反应"，一点线索都没有。
   *
   * 现在放宽到「语音 + 助/著 + 理/力/厉/里/李/手/例」这一组同音近形字。
   * 边界：**不匹配**「语音识别」「语音转文字」「语音助听器」——那些字不在集合里，
   * 开会时说这些词不会被误唤醒（有测试锁住）。
   */
  const WAKE_RE = /(语音[助著][理力厉里李手例]|助理)/;

  /* 「这是在唤产品」而不是「会议内容」。
   *
   * 提词器不该把「语音助理」当会议议题去准备话术 —— 服务端提示词里原本有一条
   * 「如果对方在叫你（喊助理），提示『应一声，问什么事』」，
   * 于是用户一喊唤醒词，面板上就跳出「应一声，问什么事」，看起来答非所问。
   *
   * 允许前后带语气词和标点（实测会说「嗯，语音助理。」），但整句不能有其他内容：
   *   "语音助理。"           → 是唤醒
   *   "语音助理，帮我算首付"  → 不是纯唤醒，仍然要提词
   */
  const WAKE_ONLY_RE = new RegExp(
    '^(好的?|嗯+|诶+|喂+)?[\\s，,、]*(语音[助著][理力厉里李手例]|助理)[\\s，,、。！？.!?]*$',
  );

  function wakeDecision({ mode, byMe, called, inWindow, micMuted }) {
    // 谁能把助理叫起来：strict 只听我的；其余档位不分谁。
    // 这一条就是「对方说'你们有助理吗'不该触发代答」的修复点。
    const maySummon = mode === 'strict' ? byMe : true;
    if (called && maySummon) return 'summon';
    if (inWindow && maySummon) return 'followup';
    if (mode === 'proxy' && !byMe && micMuted) return 'proxy';
    return null;
  }

  window.MeetWake = { wakeDecision, WAKE_RE, WAKE_ONLY_RE };
})();
